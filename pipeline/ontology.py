# ── 엣지 → 한국어 주장 문장 ──────────────────────────────────
# ★`(A) -[SUPPLIES_TO]-> (B)` 표기를 그대로 물으면 **방향을 못 읽는다.** 실측:
#   근거가 「SK하이닉스가 ASML의 EUV를 구매한다」인데
#   `(SK하이닉스) -[SUPPLIES_TO]-> (ASML)`을 두고
#   "SK하이닉스가 ASML에 장비를 공급받는 관계가 성립합니다 → supported"라고 했다.
#   화살표를 「관계가 있다」로만 읽고 방향을 무시한 것이다.
#   방향 지시문을 아무리 붙여도 안 고쳐졌고, **주장을 한국어 문장으로 펴서**
#   물으니 바로 잡혔다. 기호를 해석시키지 말고 문장을 판정하게 한다.
_CLAIM = {
    # ★역할을 **이름표로 못 박는다.** 「A가 B에 공급한다」라고만 쓰면 모델이
    #   「둘 사이에 공급 관계가 있다」는 무방향 명제로 읽어 방향을 놓친다.
    #   실측: 「SK하이닉스가 ASML에 공급한다」를 두고 "SK하이닉스가 ASML에
    #   공급**받는** 관계가 성립합니다 → 뒷받침됨"이라고 했다.
    "SUPPLIES_TO":     "파는 쪽(공급사)은 {a}이고, 사는 쪽(고객)은 {b}이다",
    "OWNS_STAKE_IN":   "주주는 {a}이고, 지분이 보유된 회사는 {b}이다",
    "IS_EXECUTIVE_OF": "{a}은(는) {b}의 임원이다",
    "ACQUIRES":        "인수하는 쪽은 {a}이고, 인수당하는 쪽은 {b}이다",
    "SUES":            "제소한 쪽(원고)은 {a}이고, 피소된 쪽(피고)은 {b}이다",
    "REGULATES":       "규제·수사·감독하는 쪽은 {a}이고, 대상 기업은 {b}이다",
    "PARTNERS_WITH":   "{a}과(와) {b}이(가) 서로 협력한다(합작·공동개발·제휴)",
    "COMPETES_WITH":   "{a}과(와) {b}이(가) 같은 제품·시장에서 경쟁한다",
    "DEVELOPS":        "{a}이(가) 「{b}」을(를) 직접 개발·생산한다",
    "DEPENDS_ON":      "{a}이(가) 「{b}」 없이는 안 될 만큼 의존한다",
    "HAS_EVENT":       "{a}이(가) 「{b}」 사건의 당사자다",
    "IMPACTS":         "「{a}」 사건이 {b}에 영향을 미친다",
}


def claim_sentence(edge: str, a: str, b: str, subtype: str = "") -> str:
    """엣지를 판정하기 쉬운 한국어 주장 문장으로 편다.

    ★subtype은 **일부러 넣지 않는다.** 넣었더니 그것 때문에 물리치는 일이 생겼다:
        엣지  삼성전자 -COMPETES_WITH/DRAM-> SK하이닉스
        근거  "삼성전자와 SK하이닉스는 HBM 시장을 사실상 양분하고 있다"
        판정  "근거는 HBM인데 주장은 DRAM이라 성립하지 않는다" → 물리침
      subtype은 추출기가 자유롭게 붙인 **참고 표현**이지 검증 대상이 아니다.
      판정 대상은 L2 엣지 유형이다.
    """
    tpl = _CLAIM.get(edge, "{a}과(와) {b}이(가) " + edge + " 관계다")
    return tpl.format(a=a or "?", b=b or "?") + "."


