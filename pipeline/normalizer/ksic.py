# LLM 프롬프트에 그대로 붙이는 선택지 표
KSIC_CHOICES = "\n".join(f"  {k} {v}" for k, v in KSIC_DIVISIONS.items())


def division_of(induty: Optional[str]) -> Optional[str]:
    """DART `induty`(5자리 세분류) → 중분류 2자리. 목록에 없으면 `99`.

    DART는 자릿수가 들쭉날쭉하다(`292`·`2612`·`29271`). 앞 2자리만 쓴다.
    """
    if not induty:
        return None
    code = str(induty).strip()[:2]
    if not code.isdigit():
        return None
    return code if code in KSIC_DIVISIONS else "99"


def label_of(code: Optional[str]) -> Optional[str]:
    """중분류 코드 → 한국어 이름."""
    return KSIC_DIVISIONS.get(code or "")
